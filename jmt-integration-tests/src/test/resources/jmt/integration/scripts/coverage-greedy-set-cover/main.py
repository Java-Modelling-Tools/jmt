import os
import subprocess
import sys
import glob

OPTIMIZER_SCRIPT = "optimize_coverage.py"   # The Set Cover Logic script
REPORT_SCRIPT    = "generate_html_report.py" # The HTML Generator script

def run_script(script_name, target_csv):
    current_dir = os.path.dirname(os.path.abspath(__file__))
    script_path = os.path.join(current_dir, script_name)
    
    if not os.path.exists(script_path):
        print(f"ERROR: Could not find '{script_name}' in: {current_dir}")
        return False

    print(f"--- Running {script_name} on {os.path.basename(target_csv)} ---")
    try:
        # Pass the specific CSV as a command line argument
        subprocess.run([sys.executable, script_path, target_csv], check=True)
        print(f"--- {script_name} Finished Successfully ---\n")
        return True
    except subprocess.CalledProcessError as e:
        print(f"!!! Notice: {script_name} did not generate data (exit code {e.returncode}).\n")
        return False

def resolve_output_dir(script_dir):
    """
    Resolves the directory containing the coverage CSVs generated by Java tests.
    Prioritizes the Maven target directory (industry golden standard) while
    retaining fallbacks for backwards compatibility and custom CLI arguments.
    """
    # 1. CLI argument override (e.g., python main.py /path/to/output)
    if len(sys.argv) > 1 and os.path.isdir(sys.argv[1]):
        return os.path.abspath(sys.argv[1])

    # 2. Environment variable
    env_dir = os.environ.get("JMT_TEST_OUTPUT_DIR")
    if env_dir and os.path.isdir(env_dir):
        return os.path.abspath(env_dir)

    # 3. Known candidate locations in priority order
    candidates = [
        # Target when run from source tree (src/test/resources/jmt/integration/scripts/coverage-greedy-set-cover)
        os.path.normpath(os.path.join(script_dir, '..', '..', '..', '..', '..', '..', '..', 'target', 'jmt', 'integration', 'output')),
        # Target when run from target/test-classes/jmt/integration/scripts/coverage-greedy-set-cover
        os.path.normpath(os.path.join(script_dir, '..', '..', '..', '..', '..', 'jmt', 'integration', 'output')),
        # Target from repository root CWD
        os.path.normpath(os.path.join(os.getcwd(), 'jmt-integration-tests', 'target', 'jmt', 'integration', 'output')),
        # Target from jmt-integration-tests module CWD
        os.path.normpath(os.path.join(os.getcwd(), 'target', 'jmt', 'integration', 'output')),
        # Fallback to target/linetesting/output (legacy build output)
        os.path.normpath(os.path.join(os.getcwd(), 'jmt-integration-tests', 'target', 'linetesting', 'output')),
        # Local output folder fallback
        os.path.normpath(os.path.join(script_dir, 'output')),
    ]

    for candidate in candidates:
        if os.path.exists(candidate) and glob.glob(os.path.join(candidate, '*_coverage.csv')):
            return candidate

    # Return primary Maven target path as default if no directory had matching CSVs yet
    return candidates[0]

def main():
    print("="*60)
    print("      JMT COVERAGE OPTIMIZATION SUITE      ")
    print("="*60)
    print("This tool will:")
    print("  1. Analyze your .csv report")
    print("  2. Select the optimal set of tests (Set Cover Algorithm).")
    print("  3. Generate an interactive HTML Dashboard for each .csv report.")
    print("-" * 60 + "\n")

    # Find all coverage CSVs generated by Java
    script_dir = os.path.dirname(os.path.abspath(__file__))
    output_dir = resolve_output_dir(script_dir)
    print(f"Looking for coverage CSVs in: {output_dir}")

    csv_pattern = os.path.join(output_dir, '*_coverage.csv')
    target_csvs = glob.glob(csv_pattern)
    
    if not target_csvs:
        print(f"Error: No coverage CSVs found matching '{csv_pattern}'")
        print("Please ensure you have run the integration tests via Maven:")
        print("  mvn test -Dtest=IntegrationTest -pl jmt-integration-tests -am")
        sys.exit(1)

    print(f"Found {len(target_csvs)} coverage files to process.")

    generated_dashboards = []
    skipped_dashboards = []

    # Process each CSV individually
    for csv_file in target_csvs:
        base_name = os.path.basename(csv_file).replace('_coverage.csv', '')
        html_path = os.path.join(script_dir, 'output', f"{base_name}_dashboard.html")

        print("\n" + "-"*60)
        print(f"PROCESSING: {os.path.basename(csv_file)}")
        print("-" * 60)
        
        if not run_script(OPTIMIZER_SCRIPT, csv_file):
            print(f"Skipping dashboard for {os.path.basename(csv_file)}: Optimizer produced no data.")
            skipped_dashboards.append((base_name, "Optimizer produced no data (CSV is empty or contains 0 covered lines)"))
            continue

        if not run_script(REPORT_SCRIPT, csv_file):
            print(f"Skipping dashboard for {os.path.basename(csv_file)}: Report generator failed.")
            skipped_dashboards.append((base_name, "Report generator could not build HTML dashboard"))
            continue

        if os.path.exists(html_path):
            generated_dashboards.append((base_name, html_path))
        else:
            skipped_dashboards.append((base_name, "Dashboard file was not created"))

    print("="*60)
    print("      PROCESS COMPLETE!      ")
    print("="*60)
    
    if generated_dashboards:
        print("Generated Dashboards (open in your browser):\n")
        for base_name, html_path in generated_dashboards:
            print(f"   [{base_name.upper()}] file://{os.path.abspath(html_path)}")
        print("\n")
    else:
        print("No dashboards were generated.\n")

    if skipped_dashboards:
        print("Dashboards skipped due to missing/incomplete test coverage:\n")
        for base_name, reason in skipped_dashboards:
            print(f"   - {base_name}: {reason}")
        print("\nTo generate the missing dashboards, run the integration tests with JaCoCo enabled:\n"
              "   # Command for ALL integration tests (recommended):\n"
              "   mvn test -Dtest=IntegrationTest -pl jmt-integration-tests -am\n"
              "   # Or run specific test suites:\n"
              "   mvn test -Dtest=IntegrationTest#testJSIMGraph -pl jmt-integration-tests -am\n"
              "   mvn test -Dtest=IntegrationTest#testJSIMWiz -pl jmt-integration-tests -am\n")

if __name__ == "__main__":
    main()
