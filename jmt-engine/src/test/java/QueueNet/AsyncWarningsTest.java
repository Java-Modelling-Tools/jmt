/**
 * The five engine warnings shown through {@link AsyncWarning}: each is provoked once and must reach the installed
 * reporter with the title and text a Swing user sees. The delay is set to 0 and the reporter signals a latch, so
 * nothing sleeps.
 */
class AsyncWarningsTest {
	private static final String TITLE = "JSIMengine - Warning";

	@TempDir
	Path dir;

	private long savedDelay;
	private LatchReporter reporter;

	/** Records warnings and counts a latch down for each one. */
	private static final class LatchReporter implements ErrorReporter {
		final CountDownLatch seen = new CountDownLatch(1);
		volatile String title;
		volatile String message;
		volatile int warnings;

		@Override
		public synchronized void warning(String title, String message) {
			this.title = title;
			this.message = message;
			warnings++;
			seen.countDown();
		}

		@Override
		public void error(String title, String message) {
			fail("unexpected error: " + message);
		}

		String await() throws InterruptedException {
			assertTrue(seen.await(5, TimeUnit.SECONDS), "warning was not reported");
			assertEquals(TITLE, title);
			return message;
		}
	}

	@BeforeEach
	void install() {
		savedDelay = AsyncWarning.delayMillis;
		AsyncWarning.delayMillis = 0;
		reporter = new LatchReporter();
		ErrorReporters.set(reporter);
	}

	@AfterEach
	void restore() {
		AsyncWarning.delayMillis = savedDelay;
		ErrorReporters.set(null);
	}

	private static RoutingStrategy[] random(int n) {
		RoutingStrategy[] r = new RoutingStrategy[n];
		java.util.Arrays.fill(r, new RandomStrategy());
		return r;
	}

	private static Queue queue() throws Exception {
		return new Queue(-1, new String[] { Queue.FINITE_DROP }, new FCFSstrategy(), new QueuePutStrategy[] { new TailStrategy() });
	}

	@Test
	void routerWarnsWhenRoutingIsDisabled() throws Exception {
		NetFixtures.Mini m = new NetFixtures.Mini(0);
		NetNode st = m.station("st", queue(), new ServiceTunnel(),
				new Router(new RoutingStrategy[] { new DisabledRoutingStrategy() }));
		NetNode next = m.station("next", new RecordingSink(), null, null);
		m.connect(m.feeder, st);
		m.connect(st, next);
		m.inject(st, 0, 0.0);
		m.run(100);
		assertEquals("st could not route one or more c0 jobs forward as its output stations are all sinks or routing is disabled.",
				reporter.await());
	}

	@Test
	void disabledServiceWarnsWhenAJobRequiresService() throws Exception {
		NetFixtures.Mini m = new NetFixtures.Mini(0);
		NetNode st = m.station("st", queue(), new Server(1, new Integer[] { 1 }, new ServiceStrategy[] { new DisabledServiceTimeStrategy() }),
				new Router(random(1)));
		NetNode sink = m.station("sink", new RecordingSink(), null, null);
		m.connect(m.feeder, st);
		m.connect(st, sink);
		m.inject(st, 0, 0.0);
		m.run(100);
		assertEquals("A c0 job requires service at st, which however is disabled.", reporter.await());
	}

	@Test
	void jobSinkWarnsWhenAForkedTaskLeavesBeforeMerging() throws Exception {
		NetFixtures.Mini m = new NetFixtures.Mini(0);
		JobSink sink = new JobSink();
		NetNode n = m.station("exit", sink, null, null);
		m.ready();
		sink.showForkJobExitWarning(m.classes[0]);
		assertEquals("A c0 task generated by a fork or scaler reached exit before merging at a join.", reporter.await());
	}

	@Test
	void jobSinkWarnsOnlyOncePerClass() throws Exception {
		NetFixtures.Mini m = new NetFixtures.Mini(0);
		JobSink sink = new JobSink();
		m.station("exit", sink, null, null);
		m.ready();
		sink.showForkJobExitWarning(m.classes[0]);
		sink.showForkJobExitWarning(m.classes[0]);
		reporter.await();
		assertEquals(1, reporter.warnings);
	}

	@Test
	void loggerWarnsWhenTheCsvCannotBeWritten() throws Exception {
		NetFixtures.Mini m = new NetFixtures.Mini(0);
		String missing = dir.resolve("missing").resolve("deeper").toString();
		LogTunnel log = new LogTunnel("log.csv", missing, true, true, true, true, true, true, true, 1);
		NetNode st = m.station("logger", queue(), log, new Router(random(1)));
		NetNode sink = m.station("sink", new RecordingSink(), null, null);
		m.connect(m.feeder, st);
		m.connect(st, sink);
		SimParameters sp = new SimParameters();
		sp.setLogPath(missing);
		sp.setLogDelimiter(",");
		sp.setLogDecimalSeparator(".");
		sp.setLogReplaceMode(String.valueOf(LoggerParameters.LOGGER_AR_REPLACE));
		sp.setTimestampValue("t0");
		st.setSimParameters(sp);
		m.inject(st, 0, 0.0);
		m.run(100);
		m.stop();
		assertEquals("logger failed to write the CSV file: " + new java.io.File(missing, "log.csv").getAbsolutePath(), reporter.await());
	}

	@Test
	void transitionWarnsWhenItReleasesFewerTasksThanItConsumed() throws Exception {
		NetFixtures.Mini m = new NetFixtures.Mini(0);
		NetNode p1 = m.station("p1", place(), new ServiceTunnel(), new Linkage());
		NetNode p2 = m.station("p2", place(), new ServiceTunnel(), new Linkage());
		Enabling enabling = new Enabling(new TransitionMatrix[] { matrix("p1", 2) }, new TransitionMatrix[] { matrix("p1", 0) });
		Timing timing = new Timing(new String[] { "mode" }, new Integer[] { 1 },
				new ServiceStrategy[] { new StrategyFixtures.ScriptedService(1.0) }, new Integer[] { -1 }, new Double[] { 1.0 });
		NetNode t = m.station("t", enabling, timing, new Firing(new TransitionMatrix[] { matrix("p2", 1) }));
		m.connect(m.feeder, p1);
		m.connect(p1, t);
		m.connect(t, p2);
		m.ready();
		for (int i = 0; i < 2; i++) {
			Job parent = m.newJob(0);
			Job fork = new ForkJob(m.classes[0], new ForkJobInfo(parent, 2, m.feeder));
			fork.initialize(m.system);
			m.feeder.send(NetEvent.EVENT_JOB, fork, 0.1 * i, NodeSection.OUTPUT, NodeSection.INPUT, p1);
		}
		m.run(1000);
		assertEquals("t failed to maintain the equilibrium between input and output tasks in mode.", reporter.await());
	}

	private static Storage place() {
		return new Storage(-1, new Integer[] { -1 }, new String[] { Storage.FINITE_DROP }, new FCFSstrategy(),
				new QueuePutStrategy[] { new TailStrategy() });
	}

	private static TransitionMatrix matrix(String station, int tokens) {
		return new TransitionMatrix(new TransitionVector[] { new TransitionVector(station, new Integer[] { tokens }) });
	}
}
