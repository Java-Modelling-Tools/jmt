import os
import subprocess
import sys
import glob

OPTIMIZER_SCRIPT = "optimize_coverage.py"   # The Set Cover Logic script
REPORT_SCRIPT    = "generate_html_report.py" # The HTML Generator script

def run_script(script_name, target_csv):
    current_dir = os.path.dirname(os.path.abspath(__file__))
    script_path = os.path.join(current_dir, script_name)
    
    if not os.path.exists(script_path):
        print(f"ERROR: Could not find '{script_name}' in: {current_dir}")
        return False

    print(f"--- Running {script_name} on {os.path.basename(target_csv)} ---")
    try:
        # Pass the specific CSV as a command line argument
        subprocess.run([sys.executable, script_path, target_csv], check=True)
        print(f"--- {script_name} Finished Successfully ---\n")
        return True
    except subprocess.CalledProcessError as e:
        print(f"!!! ERROR: {script_name} failed with exit code {e.returncode}.")
        return False

def main():
    print("="*60)
    print("      JMT COVERAGE OPTIMIZATION SUITE      ")
    print("="*60)
    print("This tool will:")
    print("  1. Analyze your .csv report")
    print("  2. Select the optimal set of tests (Set Cover Algorithm).")
    print("  3. Generate an interactive HTML Dashboard for each .csv report.")
    print("-" * 60 + "\n")

    # Find all coverage CSVs generated by Java
    script_dir = os.path.dirname(os.path.abspath(__file__))
    
    # Adjust this path if your scripts are located elsewhere!
    output_dir = os.path.join(script_dir, '..', '..', 'output')
    if not os.path.exists(output_dir):
        # Fallback to local output folder just in case
        output_dir = os.path.join(script_dir, 'output')

    csv_pattern = os.path.join(output_dir, '*_coverage.csv')
    target_csvs = glob.glob(csv_pattern)
    
    if not target_csvs:
        print(f"Error: No coverage CSVs found matching '{csv_pattern}'")
        sys.exit(1)

    print(f"Found {len(target_csvs)} coverage files to process.")

    # Process each CSV individually
    for csv_file in target_csvs:
        print("\n" + "-"*60)
        print(f"PROCESSING: {os.path.basename(csv_file)}")
        print("-" * 60)
        
        if not run_script(OPTIMIZER_SCRIPT, csv_file):
            print(f"Aborting process for {os.path.basename(csv_file)} due to error in Optimizer.")
            continue

        if not run_script(REPORT_SCRIPT, csv_file):
            print(f"Aborting process for {os.path.basename(csv_file)} due to error in Report Generator.")
            continue

    print("="*60)
    print("      PROCESS COMPLETE!      ")
    print("="*60)
    
    # Print links to all generated dashboards
    print("Open the following files in your browser:\n")
    for csv_file in target_csvs:
        base_name = os.path.basename(csv_file).replace('_coverage.csv', '')
        html_path = os.path.join(script_dir, 'output', f"{base_name}_dashboard.html")
        print(f"   file://{os.path.abspath(html_path)}")
    print("\n")

if __name__ == "__main__":
    main()